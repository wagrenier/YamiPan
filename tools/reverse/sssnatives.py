#!/usr/bin/env python3
"""The script natives' argument counts, read from the ROM: writes src/game/scriptnatives.inc.

python sssnatives.py [--list lo-hi]

Table 0x304230 holds 541 natives, ids 0x19..0x235 (index id - 0x19). A native pops its own arguments
(`m_sp -= n`, inline in each one: lw +0x9c / addiu -n / sw +0x9c) and reads its code words through the
helpers 0x1d3200 / 0x1d32e0 / 0x1d33c0 / 0x1d3410 / 0x1d3470 (one word each), so a native not written
yet can still leave the VM's stack and code position right: the VM applies these counts. The .inc is
one row {pops, words, address} per id. --list prints each native with its address, size, whether it writes the
accumulator (`acc`), yields (`yield`) and what it calls.
"""
import json
import sys

import yamipan
from elf32 import Elf

TABLE, FIRST, LAST = 0x304230, 0x19, 0x235
ARG_HELPERS = {0x1d3200, 0x1d32e0, 0x1d33c0, 0x1d3410, 0x1d3470}
YIELD = 0x1d3710
OUT = yamipan.WORK.parent.parent.parent / 'src' / 'game' / 'scriptnatives.inc'


def native(e, feats, names, id_):
    addr = e.u32(TABLE + 4 * (id_ - FIRST))
    size = feats[addr]['size']
    code = [e.u32(addr + i * 4) for i in range(size)]
    pops = words = yields = 0
    acc = False
    calls = []
    acc_slot = None
    for i, w in enumerate(code):
        op = w >> 26
        if (w & 0xffff0000) == 0xafa50000:      # sw a1,n(sp): the accumulator's address
            acc_slot = w & 0xffff
        if op == 0x2b and (w & 0xffff) == 0x9c and i and code[i - 1] >> 26 == 9:
            imm = code[i - 1] & 0xffff          # addiu r,r,-n right before sw r,0x9c(x)
            pops += 0x10000 - imm if imm & 0x8000 else -imm
        if op in (2, 3):
            target = (w & 0x3ffffff) << 2
            if target in ARG_HELPERS:
                words += 1
            elif target == YIELD:
                yields += 1
            else:
                calls.append(names.get(f'{target:08x}', hex(target)))
        if op == 0x23 and (w >> 21 & 31) == 29 and (w & 0xffff) == acc_slot:
            reg = w >> 16 & 31
            acc |= any(x >> 26 == 0x2b and x >> 21 & 31 == reg and not x & 0xffff for x in code[i + 1:i + 4])
    return dict(addr=addr, size=size, pops=pops, words=words, acc=acc, yields=yields, calls=calls)


def main():
    e = Elf(yamipan.ELF)
    feats = {f['addr']: f for f in json.load(open(yamipan.WORK / 'feat_fs2.json', encoding='utf-8'))['functions']}
    names = yamipan.cached_names()
    rows = {i: native(e, feats, names, i) for i in range(FIRST, LAST + 1)}
    if '--list' in sys.argv:
        lo, hi = (int(x, 16) for x in sys.argv[sys.argv.index('--list') + 1].split('-'))
        for i, r in rows.items():
            if lo <= i <= hi:
                print(f"{i:#x} {r['addr']:#x} {r['size']}i pops {r['pops']} words {r['words']}"
                      f"{' acc' if r['acc'] else ''}{' yield' if r['yields'] else ''} {' '.join(r['calls'])[:90]}")
        return
    lines = ['// Generated by tools/reverse/sssnatives.py from the ROM: do not edit. {pops, code words, ROM address} of each',
             '// script native, ids 0x19..0x235 in order.']
    lines += [f"/* {i:#05x} */ {{{r['pops']}, {r['words']}, {r['addr']:#x}}}," for i, r in rows.items()]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{OUT}: {len(rows)} natives')


if __name__ == '__main__':
    main()
